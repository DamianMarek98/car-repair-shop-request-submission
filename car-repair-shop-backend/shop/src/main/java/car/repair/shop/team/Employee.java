package car.repair.shop.team;

import car.repair.shop.commons.dynamodb.converter.LocalDateTimeConverter;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAttribute;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAutoGeneratedKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBHashKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBTable;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBTypeConverted;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;

import java.time.LocalDateTime;
import java.util.HashMap;
import java.util.Map;

@Getter(AccessLevel.PUBLIC)
@Setter(AccessLevel.PUBLIC)
@DynamoDBTable(tableName = "employee")
public class Employee {
    @DynamoDBHashKey
    @DynamoDBAutoGeneratedKey
    private String id;

    @DynamoDBAttribute(attributeName = "first_name")
    private String firstName;

    @DynamoDBAttribute(attributeName = "last_name")
    private String lastName;

    /** Pool for any year without a hand-typed value. */
    @DynamoDBAttribute(attributeName = "default_annual_days")
    private Integer defaultAnnualDays;

    /** Hand-typed pool per year, keyed by the 4-digit year ("2026"). */
    @DynamoDBAttribute(attributeName = "annual_days_by_year")
    private Map<String, Integer> annualDaysByYear = new HashMap<>();

    @DynamoDBAttribute(attributeName = "color_index")
    private Integer colorIndex;

    @DynamoDBAttribute(attributeName = "created_at")
    @DynamoDBTypeConverted(converter = LocalDateTimeConverter.class)
    private LocalDateTime createdAt;

    @DynamoDBAttribute(attributeName = "updated_at")
    @DynamoDBTypeConverted(converter = LocalDateTimeConverter.class)
    private LocalDateTime updatedAt;

    Integer typedPool(int year) {
        return annualDaysByYear == null ? null : annualDaysByYear.get(String.valueOf(year));
    }
}
