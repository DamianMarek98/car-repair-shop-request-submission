package car.repair.shop.team;

import car.repair.shop.commons.dynamodb.converter.LocalDateConverter;
import car.repair.shop.commons.dynamodb.converter.LocalDateTimeConverter;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAttribute;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBAutoGeneratedKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBHashKey;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBTable;
import com.amazonaws.services.dynamodbv2.datamodeling.DynamoDBTypeConverted;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;

import java.time.LocalDate;
import java.time.LocalDateTime;

/** One annual-leave range of one employee, both dates inclusive. Working days are never stored. */
@Getter(AccessLevel.PUBLIC)
@Setter(AccessLevel.PUBLIC)
@DynamoDBTable(tableName = "employee_leave")
public class Leave {
    @DynamoDBHashKey
    @DynamoDBAutoGeneratedKey
    private String id;

    @DynamoDBAttribute(attributeName = "employee_id")
    private String employeeId;

    @DynamoDBAttribute(attributeName = "start_date")
    @DynamoDBTypeConverted(converter = LocalDateConverter.class)
    private LocalDate startDate;

    @DynamoDBAttribute(attributeName = "end_date")
    @DynamoDBTypeConverted(converter = LocalDateConverter.class)
    private LocalDate endDate;

    @DynamoDBAttribute(attributeName = "created_at")
    @DynamoDBTypeConverted(converter = LocalDateTimeConverter.class)
    private LocalDateTime createdAt;

    @DynamoDBAttribute(attributeName = "updated_at")
    @DynamoDBTypeConverted(converter = LocalDateTimeConverter.class)
    private LocalDateTime updatedAt;
}
